import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {registryRowEligible,registryVisibleInWeek,registryUpdate,cleanTeamRegistry} from '../src/team-registry.js';
import {searchSettings} from '../src/settings-search.js';
const html=readFileSync('index.html','utf8'),js=readFileSync('src/legacy-app.js','utf8'),manual=readFileSync('public/manual-usuario.html','utf8');
assert.equal(JSON.parse(readFileSync('package.json')).version,'4.1.1');
assert(js.includes("APP_VERSION='4.1.1'"));
assert(html.includes('href="./manual-usuario.html"'));
assert(!html.includes('href="./MANUAL_JEFATURA_MID_MARC_V3044.pdf"'));
assert(existsSync('MANUAL_USUARIO_JEFATURA_MID_MARC_V411.md'));
assert(manual.includes('Manual de usuario') && manual.includes('Análisis del día') && manual.includes('Seguridad'));
for(const forbidden of ['cómo hostear','GitHub Pages','subir el código','deploy Edge','configurar el hosting'])assert(!manual.includes(forbidden),forbidden);
assert(html.includes('class="settings-top-actions"'));
assert(html.includes('id="settingsQuickSearch"'));
assert(!html.includes('id="settingsCategorySelect"'));
assert(!html.includes('class="jm-settings-search"'));
assert(js.includes("['Avanzado',['settingsClipboardV303','settingsResetV303','settingsAuditV27','settingsTransferV261']]"));
assert(html.includes('id="settingsClipboardV303"')&&html.includes('id="settingsResetV303"')&&html.includes('id="settingsAuditV27"'));
assert.equal(typeof searchSettings,'function');
const today=new Date(2026,10,21,12); // sábado de semana 16–22 nov
let reg=cleanTeamRegistry(null);
reg=registryUpdate(reg,'modules',{name:'Aviación',active:true,weeklyGoal:''},'', '2026-11-02');
reg=registryUpdate(reg,'executives',{name:'Iliana',active:true,weeklyGoal:'',module:'Aviación'},'','2026-11-02');
reg=registryUpdate(reg,'executives',{name:'Iliana',active:false,weeklyGoal:'',module:'Aviación'},'Iliana','2026-11-20');
const row=(date,executive='Iliana',module='Aviación')=>({fecha:date,executive,module});
assert.equal(registryVisibleInWeek(reg,'executives','Iliana','2026-11-16',today),false);
assert.equal(registryRowEligible(reg,row('2026-11-16'),today),false,'Debe ocultar lunes incluso si la baja fue el viernes de esa misma semana');
assert.equal(registryRowEligible(reg,row('2026-11-20'),today),false);
assert.equal(registryRowEligible(reg,row('2026-11-09'),today),true,'Historia anterior visible');
assert.equal(registryRowEligible(reg,row('2026-11-23'),today),false,'Fechas tras la baja siguen excluidas');
reg=registryUpdate(reg,'modules',{name:'Aviación',active:false,weeklyGoal:''},'Aviación','2026-11-21');
assert.equal(registryRowEligible(reg,row('2026-11-16','Armando'),today),false,'La baja del módulo excluye también ventas registradas en él');
assert.equal(registryRowEligible(reg,row('2026-11-09','Armando'),today),true,'Los datos históricos permanecen');
assert.equal(reg.executives.find(x=>x.name==='Iliana').active,false,'La inactivación de un módulo no cambia estado independiente de ejecutivos');
console.log('V4.1.1: inactivos semana actual, histórico, búsqueda y menú avanzado, manual accesible: OK');
