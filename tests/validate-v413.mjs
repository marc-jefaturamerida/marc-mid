import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {cleanTeamRegistry,registryUpdate,registryRowEligible,registryVisibleInWeek} from '../src/team-registry.js';
import {findMissingBaseGoals} from '../src/goals-workflow.js';
import {cleanBaseGoals} from '../src/base-goals.js';

const html=readFileSync('index.html','utf8');
const js=readFileSync('src/legacy-app.js','utf8');
const pkg=JSON.parse(readFileSync('package.json','utf8'));
const version=JSON.parse(readFileSync('public/version.json','utf8'));
assert.equal(pkg.version,'4.1.3');
assert.equal(version.version,pkg.version);
assert.match(html,/<title>Jefatura Mid Marc<\/title>/);
assert(!html.includes('<title>Jefatura Mid Marc V3.0</title>'));
assert(!html.includes('Versión 4.1.1</footer>'));
assert.equal((html.match(/<span data-app-version>4\.1\.3<\/span>/g)||[]).length,5);
assert(js.includes("const APP_VERSION='4.1.3'"));
assert(js.includes("document.querySelectorAll('[data-app-version]')"));
assert(js.includes('const rows=(data?.rows||[]).filter(row=>registryRowEligible(teamRegistry,row))'));
assert(js.includes('historyDataViewCache={source:data,registry:teamRegistry,week:todayWeek,rows}'));
assert(js.includes("registryVisibleInWeek(teamRegistry,'executives',r.executive,week)"));
assert(js.includes('const onlyCurrentWeek=Boolean(from&&to&&from>=todayWeek&&to<=weekShift(todayWeek,6))'));
assert(js.includes("registryVisibleInWeek(teamRegistry,'modules',x.module,from)"));
assert(existsSync('public/manual-usuario.html'));
assert(existsSync('.github/workflows/github-pages.yml'));

const today=new Date(2026,10,21,12);
let reg=cleanTeamRegistry(null);
reg=registryUpdate(reg,'modules',{name:'Aviación',active:true,weeklyGoal:''},'', '2026-11-02');
reg=registryUpdate(reg,'modules',{name:'Paseo Montejo',active:true,weeklyGoal:''},'', '2026-11-02');
reg=registryUpdate(reg,'executives',{name:'Armando',module:'Aviación',active:true,weeklyGoal:''},'', '2026-11-02');
reg=registryUpdate(reg,'executives',{name:'Iliana',module:'Paseo Montejo',active:true,weeklyGoal:''},'', '2026-11-02');
const row=(date,executive='Armando',module='Aviación')=>({fecha:date,executive,module});
assert(registryRowEligible(reg,row('2026-11-16'),today));
assert(registryVisibleInWeek(reg,'executives','Armando','2026-11-16',today));
reg=registryUpdate(reg,'modules',{name:'Aviación',active:false,weeklyGoal:''},'Aviación','2026-11-21');
assert.equal(registryVisibleInWeek(reg,'modules','Aviación','2026-11-16',today),false,'Módulo inactivo desaparece del listado de la semana actual');
assert.equal(registryVisibleInWeek(reg,'executives','Armando','2026-11-16',today),false,'No mostrar ejecutivo vinculado a módulo inactivo');
const pending=findMissingBaseGoals({store:cleanBaseGoals(null),registry:reg,kind:'start',todayWeek:'2026-11-16',todayDate:'2026-11-21',knownModules:['Aviación','Paseo Montejo'],knownExecutives:['Armando','Iliana']});
assert(!pending.some(item=>item.name==='Armando'||item.name==='Aviación'),'No solicitar objetivos de perfiles de un módulo inactivo');
assert.equal(registryRowEligible(reg,row('2026-11-16'),today),false,'Se oculta toda la semana actual, no solo el día de la baja');
assert.equal(registryRowEligible(reg,row('2026-11-20'),today),false,'Se ocultan filas anteriores a la baja dentro de la semana en curso');
assert.equal(registryRowEligible(reg,row('2026-11-09'),today),true,'Histórico anterior permanece');
assert.equal(registryVisibleInWeek(reg,'executives','Armando','2026-11-09',today),true,'Se conserva la consulta histórica');
assert.equal(registryRowEligible(reg,row('2026-11-16','Iliana','Paseo Montejo'),today),true,'Perfil activo en otro módulo continúa');
reg=registryUpdate(reg,'executives',{name:'Iliana',module:'Paseo Montejo',active:false,weeklyGoal:''},'Iliana','2026-11-21');
assert.equal(registryRowEligible(reg,row('2026-11-16','Iliana','Paseo Montejo'),today),false,'Ejecutivo inactivo desaparece del período actual');
assert.equal(registryRowEligible(reg,row('2026-11-09','Iliana','Paseo Montejo'),today),true,'Histórico de ejecutivo se conserva');
assert.equal(registryVisibleInWeek(reg,'executives','Iliana','2026-11-16',today),false);
console.log('V4.1.3: título, cinco pies, versión publicada e inactivos semana actual sin pérdida histórica: OK');
