import assert from 'node:assert/strict';
import {formatIncidentReport,formatUpdateReport,formatCommissionableFolios} from '../src/report-copy.js';
const incident=formatIncidentReport({folio:'123',module:'Aviación',executive:'Ana',active:true,resolved:false,comments:[{createdAt:'2026-11-17T10:00:00',text:'Revisión en proceso'}]});
assert.match(incident,/REPORTE DE INCIDENCIA/);assert.match(incident,/123/);assert.match(incident,/Revisión en proceso/);
const update=formatUpdateReport({folio:'ABC',requested_fields:{Correo:true,Teléfono:true},status:'resolved',applied_values:{Correo:'nuevo@ejemplo.mx'}});
assert.match(update,/Correo/);assert.match(update,/Actualizada/);assert.match(update,/nuevo@ejemplo.mx/);
const folios=formatCommissionableFolios([{module:'Módulo A',fecha:'2026-11-17',folio:'111'},{module:'Módulo A',fecha:'2026-11-17',folio:'111'},{module:'Módulo B',fecha:'2026-11-16',folio:'222'}]);
assert.equal(folios,'Módulo A\n17/11/2026, 111\n\nMódulo B\n16/11/2026, 222');
assert.equal(formatCommissionableFolios([]),'');
console.log('Reportes de portapapeles V3.0.1: OK');
